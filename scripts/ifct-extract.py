"""Extract per-100 g nutrient values from the IFCT 2017 data for the codes the food catalogue uses.

Source: Indian Food Composition Tables 2017 (Longvah T, Ananthan R, Bhaskarachary K, Venkaiah K;
National Institute of Nutrition, ICMR, Hyderabad), as published in the MIT-licensed npm package
`@ifct2017/compositions` (index.csv). In that file masses are in grams per 100 g edible portion and
energy is in kJ.

Usage: python3 -I scripts/ifct-extract.py <path to index.csv> > server/ifctData.ts
"""
import csv
import json
import re
import sys

CODES = sys.argv[2].split(',') if len(sys.argv) > 2 else None


def num(value):
    value = (value or '').strip()
    if value == '':
        return None
    try:
        return float(value)
    except ValueError:
        return None


def main(path):
    with open(path, newline='', encoding='utf-8') as handle:
        reader = csv.reader(handle)
        header = next(reader)
        index = {cell.split('; ')[-1]: i for i, cell in enumerate(header)}
        rows = {row[index['code']]: row for row in reader}

    # Every IFCT food is emitted: the catalogue builds its curated foods and recipes from some of
    # them, and all of them are searchable as reference foods and recipe ingredients.
    codes = sorted(rows)
    out = [
        '// Generated by scripts/ifct-extract.py — do not edit by hand.',
        '// Indian Food Composition Tables 2017 (T. Longvah et al., National Institute of Nutrition, ICMR),',
        '// via the MIT-licensed npm package @ifct2017/compositions. Values per 100 g edible portion;',
        '// null = not reported.',
        '// - Energy: IFCT kJ converted to kcal; where missing or >25 % off the food\'s own macronutrients,',
        '//   calculated from protein, fat, available carbohydrate and fibre at 17/37/17/8 kJ per g.',
        '// - Vitamin D: cholecalciferol (D3) only (see the note in scripts/ifct-extract.py).',
        '// - Omega-3: ALA + EPA + DHA.',
        '// - aliases: local-language names from IFCT (Hindi, Tamil, Telugu, …) for search.',
        '',
        "import type { Nutrients } from './foodCatalog.ts'",
        '',
        'export type IfctFood = { name: string; group: string; water: number | null; aliases: string[]; nutrients: Nutrients }',
        '',
        'export const IFCT: Record<string, IfctFood> = {',
    ]
    for code in codes:
        row = rows.get(code)
        if row is None:
            sys.exit(f'IFCT code {code} not found')
        get = lambda key: num(row[index[key]]) if key in index else None
        protein, fat, carbs, fibre = get('protcnt'), get('fatce'), get('choavldf'), get('fibtg')
        kj = get('enerc')
        computed = 17 * (protein or 0) + 37 * (fat or 0) + 17 * (carbs or 0) + 8 * (fibre or 0)
        # Use the proximate-based value when energy is missing or inconsistent with the food's own
        # macronutrients by more than 25 % (e.g. N001 chicken leg lists 1605 kJ for 19 g protein and
        # 13 g fat, about twice the calculated 798 kJ).
        if computed and (not kj or abs(kj - computed) / computed > 0.25):
            kj = computed
        mg = lambda key: None if get(key) is None else get(key) * 1000
        ug = lambda key: None if get(key) is None else get(key) * 1_000_000
        omega = [get(k) for k in ('f18d3n3', 'f20d5n3', 'f22d6n3')]
        values = {
            'energyKcal': None if kj is None else kj / 4.184,
            'proteinG': protein,
            'carbsG': carbs,
            'fatG': fat,
            'fibreG': fibre,
            'ironMg': mg('fe'),
            'calciumMg': mg('ca'),
            # Cholecalciferol (D3) only: IFCT 2017 reports ergocalciferol (D2) for cereals such as ragi
            # (41 µg/100 g) and atta (13 µg/100 g), far above other food composition databases, and
            # plant D2 bioavailability is uncertain. Counting it would make vitamin D look met (or
            # above the upper limit) from a bowl of porridge.
            'vitaminDUg': ug('chocal'),
            'zincMg': mg('zn'),
            'vitaminCMg': mg('vitc'),
            'omega3G': None if all(v is None for v in omega) else sum(v or 0 for v in omega),
        }
        body = ', '.join(f'{k}: {"null" if v is None else round(v, 3)}' for k, v in values.items())
        name = row[index['name']].strip()
        aliases = []
        for part in row[index['lang']].replace('\n', ' ').split(';'):
            part = re.sub(r'^\s*[A-Za-z]{1,5}\.\s*', '', part).strip().rstrip('.')
            for alias in part.split(','):
                alias = alias.strip().lower()
                if 2 < len(alias) <= 40 and alias != name.lower() and alias not in aliases:
                    aliases.append(alias)
        water = get('water')
        out.append(
            f"  {code}: {{ name: {json.dumps(name, ensure_ascii=False)}, group: {json.dumps(row[index['grup']].strip())}, "
            f"water: {'null' if water is None else round(water, 2)}, aliases: {json.dumps(aliases[:16], ensure_ascii=False)}, "
            f"nutrients: {{ {body} }} }},"
        )
    out.append('}')
    print('\n'.join(out))


main(sys.argv[1])
